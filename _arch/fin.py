R = lambda x: round(x, 2)
D = 1.2  # retail / 1.2 = ABO

items = {
    "Derma-Architect (127720)": 736.01,
    "Стимулиращ гел Boosting (127784)": 26.94,
    "Серум вит. C + HA (125517)": 57.66,
    "Възстановяващ омекотяващ тоник (123783)": 37.21,
    "Възстановяващ реактивиращ крем (123785)": 75.89,
    "Реактивиращ дневен крем SPF30 (123787)": 75.89,
    "Реактивиращ околоочен крем (123784)": 49.60,
    "Кремообразен разгримител (123779)": 26.78,
}
print(f"{'Продукт':<45}{'Retail €':>10}{'ABO €':>10}{'Марж €':>10}")
for k, v in items.items():
    abo = v / D
    print(f"{k:<45}{v:>10.2f}{abo:>10.2f}{v-abo:>10.2f}")

print(f"\nОтстъпка ABO спрямо retail: {100*(1-1/D):.2f}%  (заданието твърдеше ~22%)")

# Стартова инвестиция, минимален работещ комплект
start = ["Derma-Architect (127720)", "Стимулиращ гел Boosting (127784)",
         "Серум вит. C + HA (125517)", "Възстановяващ омекотяващ тоник (123783)",
         "Кремообразен разгримител (123779)", "Възстановяващ реактивиращ крем (123785)"]
tot_abo = sum(items[k]/D for k in start)
print(f"\nМинимален стартов комплект (ABO): {tot_abo:.2f} €")
print(f"  + 2 резервни гела: {tot_abo + 2*items['Стимулиращ гел Boosting (127784)']/D:.2f} €")
print(f"Остатък от бюджет 2000 €: {2000 - (tot_abo + 2*items['Стимулиращ гел Boosting (127784)']/D):.2f} €")

# Себестойност на процедура - чувствителност по брой приложения от туба гел
gel_abo = items["Стимулиращ гел Boosting (127784)"] / D
serum_abo = items["Серум вит. C + HA (125517)"] / D
print("\n--- Себестойност/процедура, чувствителност (тубата гел = N приложения) ---")
print(f"{'N':>4}{'гел €':>10}{'серум €*':>10}{'общо €':>10}{'марж @35€':>12}{'марж %':>9}")
for N in (20, 25, 30, 40):
    g = gel_abo / N
    s = serum_abo / 30   # * ДОПУСКАНЕ: 30 приложения/флакон - изисква измерване
    c = g + s
    print(f"{N:>4}{g:>10.2f}{s:>10.2f}{c:>10.2f}{35-c:>12.2f}{100*(35-c)/35:>8.1f}%")

# Капацитет
print("\n--- Капацитет/ден (лимит: 5 употреби, после 10 мин охлаждане) ---")
for proc_min in (25, 45, 55):
    cycle = proc_min + 10  # почистване/подготовка
    per_8h = int(480 / cycle)
    print(f"  процедура {proc_min} мин + 10 мин оборот = {cycle} мин -> {per_8h} клиента/8ч")

# Break-even само на процедури
print("\n--- Break-even само от процедури (без продажба на уред) ---")
for price, cost in ((25, 1.9), (35, 1.9), (45, 1.9)):
    n = tot_abo / (price - cost)
    print(f"  цена {price} € -> {n:.0f} процедури за покриване на {tot_abo:.0f} € стартова инвестиция")

print("\n--- Break-even чрез продажба на уреди ---")
dev_margin = items["Derma-Architect (127720)"] - items["Derma-Architect (127720)"]/D
print(f"  Марж на продаден уред (retail - ABO): {dev_margin:.2f} €")
print(f"  Брой продадени уреда за покриване на стартовата инвестиция: {tot_abo/dev_margin:.1f}")
